const INDEX: Record<L2PatternId, L2VisualPattern> = ALL_L2_PATTERNS.reduce(
  (acc, p) => {
    acc[p.id] = p;
    return acc;
  },
  {} as Record<L2PatternId, L2VisualPattern>,
);

export function getL2Pattern(id: L2PatternId): L2VisualPattern {
  const p = INDEX[id];
  if (!p) throw new Error(`Unknown L2 pattern: ${id}`);
  return p;
}

export type {
  L2VisualPattern,
  L2PatternId,
  L2PatternCategory,
  L2Reliability,
} from "./types";
